// ── Helpers to build typed inputs from fixture data ──────────────────────

export function buildMenagesEvolution(fixture: FlowRequirementFixture): TGetDemographicEvolution[] {
  const { epciCode, omphaleKey } = fixture.config
  return Object.entries(fixture.data.menagesProjection)
    .sort(([a], [b]) => Number(a) - Number(b))
    .map(([year, value]) => ({
      epciCode,
      [omphaleKey]: value,
      year: Number(year),
    }))
}

export function buildDemographicEvolution(fixture: FlowRequirementFixture): TDemographicEvolution {
  const { omphaleKey } = fixture.config
  const menages = buildMenagesEvolution(fixture)
  const sorted = menages.sort((a, b) => a.year - b.year)

  const yearlyData = sorted.map((projection, index) => {
    const currentValue = projection[omphaleKey] as number
    const previousValue = index > 0 ? (sorted[index - 1][omphaleKey] as number) : currentValue
    return {
      value: currentValue - previousValue,
      year: projection.year,
      yearValue: currentValue,
      previousYearValue: previousValue,
    }
  })

  const values = yearlyData.map((d) => d.value)
  return {
    data: yearlyData,
    metadata: {
      data: { max: Math.max(...values), min: Math.min(...values) },
      period: { startYear: yearlyData[0].year, endYear: yearlyData[yearlyData.length - 1].year },
    },
  }
}

