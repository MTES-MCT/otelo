-- Garde-fou : les clés étrangères font déjà échouer la migration si un libellé de bassin ou un
-- code EPCI a disparu, mais elles ne disent rien de la complétude. Si le référentiel géographique
-- a dérivé depuis la génération de ce bloc, mieux vaut interrompre le déploiement que charger un
-- référentiel amputé, sur lequel l'import rejetterait ensuite des zones entières.
DO $$
DECLARE
  nb_total int;
  nb_epci int;
  nb_bassins int;
BEGIN
  SELECT count(*),
         count(*) FILTER (WHERE "epci_code" IS NOT NULL),
         count(DISTINCT "bassin_name") FILTER (WHERE "level" = 'BH')
    INTO nb_total, nb_epci, nb_bassins
    FROM "projection_zones";

  IF nb_total <> 561 OR nb_epci <> 226 OR nb_bassins <> 335 THEN
    RAISE EXCEPTION 'Référentiel des projections incohérent : % zones, % rattachées à un EPCI, % bassins couverts (attendu 561 / 226 / 335)',
      nb_total, nb_epci, nb_bassins;
  END IF;
END $$;
