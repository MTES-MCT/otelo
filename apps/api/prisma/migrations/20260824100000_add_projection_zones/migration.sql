-- Référentiel des zones du fichier « Projections détaillées » Omphale.
--
-- Le fichier livre ses projections à deux niveaux : les 214 EPCI d'au moins 50 000 habitants en
-- 2018 (seuil de robustesse Omphale) et 347 bassins d'habitat. Les codes des deux niveaux sont
-- disjoints par construction — SIREN à 9 chiffres d'un côté, `R11_01_23` / `Paris_23` /
-- `ZZZZZZZZZ` de l'autre — d'où un référentiel unique plutôt qu'un par niveau.
--
-- RATTACHEMENT AU RÉFÉRENTIEL OTELO
--
-- Le fichier désigne ses bassins par un code technique qu'aucune table Otelo ne porte : `bassin`
-- a pour clé primaire son libellé. Le raccord passe par la table de passage INSEE
-- (« Table de passage EPCI - BH.xlsx », colonnes BH_INSEE → LIB_BH), dont les libellés sont
-- antérieurs à 20260823120000_rename_bassins_aout_2026 et doivent donc lui être repassés, avec
-- trois normalisations :
--   1. les 49 renommages de cette migration ;
--   2. la forme héritée « Bassin d'habitat de <X> », où <X> est le libellé du référentiel amputé
--      de son préfixe technique `QZE `/`ZO ` ;
--   3. le tiret demi-cadratin (U+2013) là où le référentiel utilise un trait d'union ordinaire.
-- La table de passage orthographie par ailleurs un code avec une barre oblique (`R28/24_09_23`)
-- là où le fichier utilise un tiret bas — c'est le bassin PERCHE.
--
-- 334 bassins se résolvent ainsi, de façon bijective.
--
-- LES 12 EPT DU GRAND PARIS
--
-- Les 13 zones restantes ne figurent pas dans la table de passage. Douze sont les territoires de
-- la Métropole du Grand Paris, qu'Otelo connaît déjà : ils existent dans `epcis` sous les codes
-- composites `200054781_T1` … `_T12`, tous rattachés au bassin « PARIS MÉTROPOLE ». Chaque zone
-- reçoit donc son EPCI *et* ce bassin. La partition est vérifiée : la somme des 12 zones vaut
-- 7 075 048 habitants en 2018, soit exactement la population de la métropole.
--
-- ⚠ Deux de ces EPT ne sont pas projetés (`ind_robust = 0`, année 2018 seule) : `R11_BCN_23`
-- (Boucle Nord de Seine) et `R11_GOSB_23` (Grand-Orly Seine Bièvre). Agréger les 12 EPT au-delà
-- de 2018 amputerait la métropole de 1 155 847 habitants, soit 16 %. C'est
-- `projection_zone_millesimes.is_robust` qui porte cette information jusqu'à l'API.
--
-- La treizième, `ZZZZZZZZZ`, est la zone résiduelle du fichier (6 277 habitants) : aucun
-- territoire ne lui correspond. Elle est chargée avec ses données et un rattachement vide, plutôt
-- que perdue — c'est la raison pour laquelle les tables de mesures référencent `projection_zones`
-- et jamais `bassin` directement.
--
-- POURQUOI CE RÉFÉRENTIEL EST ICI ET NON DANS LA COMMANDE D'IMPORT
--
-- La table de passage INSEE n'est pas versionnée avec le code et n'existe ni sur la CI ni en
-- production, alors que le déploiement joue `prisma migrate deploy` et que les tables de mesures
-- ont besoin du référentiel en place pour satisfaire leur clé étrangère. Le bloc VALUES est
-- généré par `pnpm -F api cli import-projections --emit-zones-sql --passage-file <...>`, pas
-- saisi à la main.

